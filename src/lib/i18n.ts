export function localize(value: LocalizedText | undefined, language: Language): string {
  if (!value) return "";
  return value[language] || value[DEFAULT_LANGUAGE] || "";
}

export function normalizeLanguage(value: string | null | undefined): Language | null {
  return value === "en" || value === "ko" ? value : null;
}
