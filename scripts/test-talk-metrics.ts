import assert from "node:assert/strict";
import { seedContent } from "../src/data/seed";
import { getTalkMetrics } from "../src/lib/talkMetrics";
import type { TimelineItem } from "../src/types/content";

const record: TimelineItem = { ...seedContent.timeline.find((item) => item.section === "talks")!, highlights: undefined, description: { en: "", ko: "" } };
const highlight = (en: string, ko = "") => ({ id: en || ko, title: { en, ko }, description: { en: "", ko: "" }, imageUrl: "", links: [] });
assert.deepEqual(getTalkMetrics([]), { engagements: 0, activeYears: 0, talksLecturesPresentations: 0, interviewsMedia: 0, panelsRoundtables: 0, mentoringSessions: 0 });
const items = [{ ...record, highlights: [highlight("A technical lecture"), highlight("Video interview"), highlight("Panelist and speaker"), highlight("Career mentoring")] }];
const metrics = getTalkMetrics(items);
assert.equal(metrics.engagements, 4);
assert.equal(metrics.talksLecturesPresentations, 1);
assert.equal(metrics.interviewsMedia, 1);
assert.equal(metrics.panelsRoundtables, 1);
assert.equal(metrics.mentoringSessions, 1);
assert.equal(getTalkMetrics([{ ...items[0], section: "career" }]).engagements, 0);
assert.equal(getTalkMetrics([{ ...items[0], description: { en: "- Video interview", ko: "- 인터뷰" } }]).engagements, 4, "highlights replace description");
assert.equal(getTalkMetrics([{ ...record, description: { en: "- Talk\n- Interview\n- Roundtable", ko: "- 강연\n- 인터뷰\n- 간담회" } }]).engagements, 3, "translations count once");
assert.equal(getTalkMetrics([{ ...record, highlights: [highlight("", "간담회")]}]).panelsRoundtables, 1, "Korean format recognition");
assert.equal(getTalkMetrics([{ ...record, title: { en: "Interview", ko: "인터뷰" } }]).interviewsMedia, 1, "standalone records");
assert.equal(getTalkMetrics([{ ...items[0], period: "2026" }, { ...items[0], period: "2026" }]).activeYears, 1, "distinct years");
const edited = [{ ...record, highlights: [highlight("Video interview")] }];
assert.equal(getTalkMetrics(edited).interviewsMedia, 1);
edited[0].highlights = [highlight("Technical presentation")];
assert.equal(getTalkMetrics(edited).interviewsMedia, 0, "live edits change format totals");
assert.equal(getTalkMetrics(edited).talksLecturesPresentations, 1);
assert.equal(getTalkMetrics([...items, ...edited]).engagements, 5, "new database entries increase total");
const seed = getTalkMetrics(seedContent.timeline);
assert.equal(seed.engagements, seed.talksLecturesPresentations + seed.interviewsMedia + seed.panelsRoundtables + seed.mentoringSessions, "seed categories partition entries");
assert.ok(seed.engagements > 0, "fallback remains useful");
console.log("Talk metrics checks passed: live edits, formats, bilingual digests, fallback, standalone records, and filtering.");
