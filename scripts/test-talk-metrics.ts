import assert from "node:assert/strict";
import { seedContent } from "../src/data/seed";
import { getTalkMetrics } from "../src/lib/talkMetrics";
import type { TimelineItem } from "../src/types/content";

const record: TimelineItem = { ...seedContent.timeline.find((item) => item.section === "talks")!, highlights: undefined, description: { en: "", ko: "" } };
const highlight = (tags: string[], en = "Video interview panel mentoring", ko = "인터뷰 패널 멘토링") => ({ id: "entry", tags, title: { en, ko }, description: { en: "", ko: "" }, imageUrl: "", links: [] });
const metrics = getTalkMetrics([{ ...record, highlights: [highlight(["lecture", "presentation"]), highlight(["interview"]), highlight(["panel"]), highlight(["mentoring"])] }]);
assert.deepEqual(metrics, { engagements: 4, activeYears: 1, talksLecturesPresentations: 2, interviewsMedia: 1, panelsRoundtables: 1, mentoringSessions: 1 });
assert.equal(getTalkMetrics([{ ...record, section: "career", highlights: [highlight(["lecture"])] }]).engagements, 0);
const unclassified = getTalkMetrics([{ ...record, highlights: [highlight([])] }]);
assert.equal(unclassified.engagements, 1);
assert.equal(unclassified.interviewsMedia + unclassified.talksLecturesPresentations + unclassified.panelsRoundtables + unclassified.mentoringSessions, 0, "titles do not classify entries and explicit empty labels do not inherit");
const overlapping = getTalkMetrics([{ ...record, highlights: [highlight(["media", "interview", "panel", "roundtable", "lecture", "mentoring", "lecture"])] }]);
assert.equal(overlapping.engagements, 1);
assert.equal(overlapping.interviewsMedia, 1);
assert.equal(overlapping.panelsRoundtables, 1);
assert.equal(overlapping.talksLecturesPresentations, 1);
assert.equal(overlapping.mentoringSessions, 1);
assert.equal(getTalkMetrics([{ ...record, tags: ["interview"], highlights: [{ ...highlight([]), tags: undefined }] }]).interviewsMedia, 1, "legacy lines inherit parent labels");
assert.equal(getTalkMetrics([{ ...record, tags: ["presentation"], description: { en: "- Interview\n- Panel", ko: "- 인터뷰\n- 패널" } }]).talksLecturesPresentations, 2, "legacy bullets count translations once using parent labels");
assert.equal(getTalkMetrics([{ ...record, tags: ["media"] }]).interviewsMedia, 1, "standalone item labels");
assert.equal(getTalkMetrics([{ ...record, highlights: [] }]).engagements, 0);
assert.equal(getTalkMetrics([{ ...record, highlights: [highlight(["lecture"], "", "")] }]).engagements, 0);
const edited = { ...record, highlights: [highlight(["interview"])] };
assert.equal(getTalkMetrics([edited]).interviewsMedia, 1);
edited.highlights = [highlight(["presentation"])];
assert.equal(getTalkMetrics([edited]).interviewsMedia, 0);
assert.equal(getTalkMetrics([edited]).talksLecturesPresentations, 1, "label edits update counts without changing title");
assert.equal(getTalkMetrics([{ ...edited, period: "2026" }, { ...edited, period: "2026" }]).activeYears, 1);
assert.ok(getTalkMetrics(seedContent.timeline).talksLecturesPresentations > 0, "seed fallback remains useful");
console.log("Label-based metrics checks passed: overlaps, deduplication, missing labels, legacy fallback, live edits, bilingual records, and seed content.");

assert.equal(getTalkMetrics([{ ...record, highlights: [highlight(["panel", "roundtable"])] }]).talksLecturesPresentations, 1, "panel and roundtable labels count once in combined speaking metric");
